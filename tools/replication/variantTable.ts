/**
 * Generates docs/replication/variant-comparison.md: results under the printed equations, the
 * figure-replication variant, and values read off the published figures.
 *
 *   npm run replication:variants
 */
import { writeFileSync } from 'node:fs';
import { PAPER_PRESET_ID, paperParameters } from '../../src/economics/paper/calibration';
import { existenceBoundary } from '../../src/economics/paper/existence';
import { solveSteadyStateDual } from '../../src/economics/paper/steadyState';
import type { EquationVariant, SteadyStateResult, Technology } from '../../src/economics/paper/types';

const VARIANTS: Record<string, EquationVariant> = {
  'Printed eqs (1) & (24)': { techAWeight: 'asPrinted', labourSupply: 'asPrinted' },
  'Default: θ on K, printed (24)': { techAWeight: 'capitalWeight', labourSupply: 'asPrinted' },
  'Figure replication: θ on K, (24) without wedges': {
    techAWeight: 'capitalWeight',
    labourSupply: 'figureReplication',
  },
};

/**
 * Values read visually off the published figures (no digitisation software); reading uncertainty
 * is roughly ±0.01 on shares/ratios and ±5% on levels. They are NOT used to tune anything.
 */
const PUBLISHED: Record<string, { value: number; source: string }> = {
  ssToGdp: { value: 0.151, source: 'Fig. 1 intercept' },
  grossLabour: { value: 0.59, source: 'Fig. 8/9 intercept' },
  grossTraditionalCapital: { value: 0.31, source: 'Fig. 8 (flat line)' },
  netLabour: { value: 0.84, source: 'Fig. 10/11 intercept' },
  netTraditionalCapital: { value: 0.16, source: 'Fig. 10/11 intercept' },
  L: { value: 0.33, source: 'Fig. 6/7 labour' },
  Y: { value: 0.6, source: 'Fig. 6/7 output' },
  K: { value: 2.0, source: 'Fig. 6/7 traditional capital' },
  C: { value: 0.48, source: 'Fig. 6/7 consumption' },
};
const FIG1: Record<Technology, [number, number][]> = {
  A: [
    [0.1, 0.145],
    [0.2, 0.125],
    [0.3, 0.09],
    [0.4, 0.035],
  ],
  B: [
    [0.1, 0.145],
    [0.2, 0.125],
    [0.3, 0.095],
    [0.4, 0.05],
    [0.45, 0.022],
  ],
};

const f = (x: number | undefined, d = 4) => (x === undefined || !Number.isFinite(x) ? '—' : x.toFixed(d));
function pick(r: SteadyStateResult, key: string): number | undefined {
  if (!r.ok) return undefined;
  if (key === 'ssToGdp') return r.ssToGdp;
  if (key in r.shares) return r.shares[key as keyof typeof r.shares];
  return r.levels[key as keyof typeof r.levels];
}

const lines: string[] = [];
lines.push('# Equation-variant comparison (generated)', '');
lines.push(
  `Generated by \`tools/replication/variantTable.ts\` from the TS model (solver: dual; preset: \`${PAPER_PRESET_ID}\`).`,
);
lines.push(
  'Do not edit by hand. Published values are visual readings of the figures (≈ ±0.01 on ratios, ±5% on levels).',
  '',
);
lines.push('## Baseline (adoption 0, no robot tax), Technology A', '');
const names = Object.keys(VARIANTS);
lines.push(
  `| Quantity | ${names.join(' | ')} | Published | Source |`,
  `|---|${names.map(() => '---:').join('|')}|---:|---|`,
);
const base = names.map((n) =>
  solveSteadyStateDual(paperParameters('A', { variant: VARIANTS[n]! }), {
    calibrationPreset: PAPER_PRESET_ID,
  }),
);
for (const [key, pub] of Object.entries(PUBLISHED)) {
  lines.push(
    `| ${key} | ${base.map((r) => f(pick(r, key))).join(' | ')} | ${f(pub.value, 3)} | ${pub.source} |`,
  );
}
lines.push(
  '',
  'Rows L, Y, K, C are levels and depend on eq. (24); every other row is a ratio and does not (Proposition 1).',
  '',
);

lines.push('## SS contributions / GDP vs adoption, no robot tax (Fig. 1)', '');
for (const tech of ['A', 'B'] as const) {
  const b = existenceBoundary(paperParameters(tech));
  lines.push(
    `### Technology ${tech} (existence boundary ${b.kind === 'boundary' ? b.adoption.toFixed(5) : b.kind})`,
    '',
  );
  lines.push(
    `| Adoption | ${names.join(' | ')} | Published (Fig. 1) |`,
    `|---:|${names.map(() => '---:').join('|')}|---:|`,
  );
  for (const [a, pub] of FIG1[tech]) {
    const rs = names.map((n) =>
      solveSteadyStateDual(paperParameters(tech, { adoption: a, variant: VARIANTS[n]! })),
    );
    lines.push(
      `| ${a} | ${rs.map((r) => (r.ok ? f(r.ssToGdp) : `no SS (${r.reason})`)).join(' | ')} | ${f(pub, 3)} |`,
    );
  }
  lines.push('');
}
lines.push('Note: the "Printed eqs" column differs only for Technology A, because D1 concerns eq. (1).');
writeFileSync('docs/replication/variant-comparison.md', lines.join('\n') + '\n');
console.log('wrote docs/replication/variant-comparison.md');
