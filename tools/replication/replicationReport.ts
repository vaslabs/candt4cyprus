/**
 * Generates the reproducible replication report and the curve data behind Figs 1–11.
 *
 *   npm run replication:report
 *     → docs/replication/REPLICATION_REPORT.md
 *     → docs/replication/data/curves.csv
 *
 * Output is deterministic (no timestamps), so a diff shows exactly what changed in the model.
 */
import { mkdirSync, writeFileSync } from 'node:fs';
import { PAPER_PRESET_ID, paperParameters } from '../../src/economics/paper/calibration';
import { evaluateBenchmarks, KNOWN_DISCREPANCIES } from '../../src/economics/paper/replication';
import {
  baselineSsTarget,
  ROBOT_TAX_SCHEMES,
  SCHEME_INFO,
  solveRequiredRobotTax,
  sweepAdoption,
  type RobotTaxScheme,
} from '../../src/economics/policies/robotTaxes';
import { techAClosedFormRates } from '../../src/economics/policies/closedForms';
import { DEFAULT_VARIANT, type Technology } from '../../src/economics/paper/types';

const f = (x: number | null | undefined, d = 4) =>
  x === null || x === undefined || !Number.isFinite(x) ? '—' : x.toFixed(d);
const L: string[] = [];
const results = evaluateBenchmarks();
const passed = results.filter((r) => r.pass).length;

L.push('# Replication report: Casas & Torres (2026)', '');
L.push(
  '*Generated by `tools/replication/replicationReport.ts` (`npm run replication:report`). Do not edit by hand.*',
  '',
);
L.push('| Setting | Value |', '|---|---|');
L.push(`| Calibration preset | \`${PAPER_PRESET_ID}\` (paper Table 1) |`);
L.push(
  `| Equation variant | Tech A weight: \`${DEFAULT_VARIANT.techAWeight}\`; eq. (24): \`${DEFAULT_VARIANT.labourSupply}\` (see MODEL_DEVIATIONS D1, D2) |`,
);
L.push(
  '| Solver | `dual` (semi-analytic). Cross-checked against the full Newton system and the Python/SciPy oracle |',
);
L.push('| Policy target | SS/Y of the same economy at zero adoption without robot taxes |');
L.push('');
L.push(
  'Under Proposition 1, the eq. (24) variant affects only levels (Y, C, K, D, L), never the tax rates, shares or SS/Y below.',
  '',
);
L.push('## Summary', '');
L.push(`**${passed} of ${results.length} benchmarks pass** at tolerances fixed before computing.`);
L.push(
  `The ${results.length - passed} failures are documented discrepancies, explained below. They are not hidden or tuned away.`,
  '',
);
L.push('**What replicates.**');
L.push('- Every headline tax rate is reproduced within ±0.002:');
L.push('  - robot income tax: 0.56 (Tech A), 0.48 (Tech B);');
L.push('  - investment tax: 0.38 (A), 0.23 (B);');
L.push('  - robot SS contribution: 0.28 (A), 0.18 (B).');
L.push('- The baseline SS/GDP ratio is reproduced.');
L.push('- The crossover where robots pay half of SS falls at adoption 0.35–0.39.');
L.push('- The robot SS contribution is the least distortionary of the three taxes.');
L.push('- Gross labour-share effects and their ordering, and the flat Tech A capital share, are reproduced.');
L.push('- The Tech B rate paths across adoption are reproduced.', '');
L.push('**What does not.**');
L.push('- The Tech A low-adoption transients in Figs 2–4.');
L.push('- The net-income-share rankings (Figs 10–11).');
L.push('- The phrase "robots ≈ 35% of total capital".', '');
L.push('## Benchmarks', '');
L.push('| ID | Claim | Source | Published | Computed | Abs. error | Tolerance | Result |');
L.push('|---|---|---|---:|---|---:|---|:---:|');
for (const r of results) {
  L.push(
    `| ${r.id} | ${r.claim} | ${r.source} | ${r.published} | ${r.computed} | ${r.absError === undefined ? '' : r.absError.toFixed(4)} | ${r.tolerance} | ${r.pass ? 'PASS' : '**FAIL**'} |`,
  );
}
L.push('', 'Notes per benchmark:', '');
for (const r of results.filter((x) => x.note)) L.push(`- **${r.id}**: ${r.note}`);
L.push('');

L.push('## Documented discrepancies', '');
for (const [id, why] of Object.entries(KNOWN_DISCREPANCIES)) L.push(`- **${id}**: ${why}`);
L.push('');

L.push('### Tech A rates are exactly constant (Proposition 3)', '');
const cf = techAClosedFormRates(paperParameters('A'));
L.push(
  'Under Technology A, R_k alone fixes the cost share of the effective-labour aggregate X. Labour and robot costs exhaust that share.',
);
L.push(
  'So the rate that holds SS/Y at its zero-adoption level does not depend on adoption φ or on the elasticity υ, and it has closed forms (MODEL_SPEC §5a):',
  '',
);
L.push(`| Scheme | Closed form | Value | Paper |`, '|---|---|---:|---:|');
L.push(`| τ^ssz | (τ^sse+τ^ssw)/(1−τ^ssw) | ${f(cf.robotSS)} | 0.28 |`);
L.push(`| τ^d | a(1/β−1+(1−τ^k)δ_d)/(1/β−1+aδ_d), a=(τ^sse+τ^ssw)/(1+τ^sse) | ${f(cf.robotIncome)} | 0.56 |`);
L.push(`| τ^id | a(1/β−1+(1−τ^k)δ_d)/((1−τ^k)δ_d−a(1/β−1+δ_d)) | ${f(cf.robotInvestment)} | 0.38 |`);
L.push('');
L.push(
  'The paper says Tech A rates converge to these values "regardless of the elasticity". In the exact solution they are equal to them at every adoption level.',
);
L.push(
  'The elevated rates the paper plots at low adoption cannot come from an exact solution with the stated target.',
  '',
);
L.push(
  '**Hypothesis H1 (not adopted).** The transients are consistent with a target slightly *above* the model’s own zero-adoption SS/Y.',
);
L.push('Near φ = 0 a vanishing robot base must then cover a fixed gap, so the rate spikes.');
L.push(
  'The table shows the Tech A robot income tax (υ = 2) under small target offsets. Compare Fig. 2 (≈ 0.62 near φ = 0.02, ≈ 0.57 at 0.05, ≈ 0.56 by 0.2):',
  '',
);
const base = baselineSsTarget(paperParameters('A'));
const phis = [0.02, 0.05, 0.1, 0.2, 0.3];
L.push(`| Target | ${phis.map((x) => `φ=${x}`).join(' | ')} |`, `|---|${phis.map(() => '---:').join('|')}|`);
for (const d of [0, 0.0002, 0.0005, 0.001]) {
  const row = phis.map((a) => {
    const r = solveRequiredRobotTax(paperParameters('A', { adoption: a }), 'robotIncome', {
      target: base + d,
    });
    return r.status === 'solved' ? f(r.rate, 3) : r.status;
  });
  L.push(`| ${f(base, 4)} + ${d} | ${row.join(' | ')} |`);
}
L.push('');

L.push('### Net income shares (D3)', '');
L.push(
  'The paper does not define net shares. We use (factor income − its depreciation)/(Y − total depreciation), with labour income including employer SS.',
);
L.push(
  'At baseline this gives net labour 0.862, against ≈ 0.84 in the figures. Under this definition the paper’s net-share results (B10, stated on p. 94: Tech A taxes converge to one share; Tech B only τ^ssz ends above no tax) do not reproduce.',
);
L.push('The definition is deliberately **not** adjusted to match.', '');

L.push('## Required rates across adoption (Figs 2–4)', '');
for (const scheme of ROBOT_TAX_SCHEMES) {
  L.push(
    `### ${SCHEME_INFO[scheme].label}: ${SCHEME_INFO[scheme].symbol}, base ${SCHEME_INFO[scheme].base}`,
    '',
  );
  const grid = [0.02, 0.05, 0.1, 0.15, 0.2, 0.3, 0.4, 0.45];
  L.push(
    `| Tech | Elasticity | ${grid.map((a) => `${a}`).join(' | ')} |`,
    `|---|---:|${grid.map(() => '---:').join('|')}|`,
  );
  for (const tech of ['A', 'B'] as const) {
    for (const e of [1, 2, 3]) {
      const row = grid.map((a) => {
        const r = solveRequiredRobotTax(paperParameters(tech, { adoption: a, elasticityAuto: e }), scheme);
        if (r.status !== 'solved') return r.status === 'unattainable' ? 'unatt.' : r.status;
        return `${f(r.rate, 3)}${r.untaxedSteadyStateExists ? '' : '†'}`;
      });
      L.push(`| ${tech} | ${e} | ${row.join(' | ')} |`);
    }
  }
  L.push('');
}
L.push(
  '"unatt." means no admissible rate reaches the target. The paper also omits these points ("considering only feasible scenarios").',
);
L.push(
  '† means the untaxed economy has no finite steady state at that adoption level; the tax is needed for one to exist.',
  '',
);

// ------------------------------------------------------------------ CSV
const rows: string[] = [
  'technology,scheme,elasticityAuto,adoption,status,rate,Y,C,I,L,K,D,W,ssToGdp,labourSourceShare,robotSourceShare,grossLabour,grossTraditionalCapital,grossAutonomousCapital,netLabour,netTraditionalCapital,netAutonomousCapital',
];
const grid = Array.from({ length: 91 }, (_, i) => i / 200);
for (const tech of ['A', 'B'] as Technology[]) {
  for (const e of [1, 2, 3]) {
    for (const scheme of ['none', ...ROBOT_TAX_SCHEMES] as RobotTaxScheme[]) {
      for (const pt of sweepAdoption(paperParameters(tech, { elasticityAuto: e }), scheme, grid)) {
        const r = pt.result?.ok ? pt.result : null;
        const v = (x: number | undefined | null) =>
          x === undefined || x === null || !Number.isFinite(x) ? '' : x.toPrecision(10);
        rows.push(
          [
            tech,
            scheme,
            e,
            pt.adoption,
            pt.status,
            v(pt.rate),
            v(r?.levels.Y),
            v(r?.levels.C),
            v(r?.levels.I),
            v(r?.levels.L),
            v(r?.levels.K),
            v(r?.levels.D),
            v(r?.levels.W),
            v(r?.ssToGdp),
            v(pt.labourSourceShare),
            v(pt.robotSourceShare),
            v(r?.shares.grossLabour),
            v(r?.shares.grossTraditionalCapital),
            v(r?.shares.grossAutonomousCapital),
            v(r?.shares.netLabour),
            v(r?.shares.netTraditionalCapital),
            v(r?.shares.netAutonomousCapital),
          ].join(','),
        );
      }
    }
  }
}
L.push('## Data', '');
L.push(
  '`docs/replication/data/curves.csv` has every curve (both technologies, elasticities 1–3, all four schemes, adoption 0–0.45 in steps of 0.005), with status per point.',
);
L.push('Points without a steady state have empty values; they are never interpolated.');
L.push(
  'Levels in the CSV use the default (printed) eq. (24). Use the figure-replication variant to compare levels with Figs 6–7.',
  '',
);

mkdirSync('docs/replication/data', { recursive: true });
writeFileSync('docs/replication/REPLICATION_REPORT.md', L.join('\n') + '\n');
writeFileSync('docs/replication/data/curves.csv', rows.join('\n') + '\n');
console.log(
  `wrote docs/replication/REPLICATION_REPORT.md (${passed}/${results.length} pass) and curves.csv (${rows.length - 1} rows)`,
);
