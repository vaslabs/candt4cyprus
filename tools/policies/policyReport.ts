/**
 * Generates docs/policies/POLICY_COMPARISON.md (deterministic). Run: npm run policies:report
 */
import { writeFileSync, mkdirSync } from 'node:fs';
import { calibrateCyprus, type CalibrationResult } from '../../src/economics/cyprus/calibration';
import {
  cyprusAssumptions,
  cyprusMonthlyEarnings,
  cyprusNationalAccounts2023,
  cyprusStatutoryRules,
  loadCyprusDataset,
} from '../../src/economics/cyprus/defaults';
import { contributionsExclState, fundSeries } from '../../src/economics/cyprus/fundAccounts';
import { solveWithCeiling } from '../../src/economics/cyprus/ceilingFeedback';
import { existenceBoundary } from '../../src/economics/paper/existence';
import { paperParameters } from '../../src/economics/paper/calibration';
import { baselineSsTarget } from '../../src/economics/policies/robotTaxes';
import {
  DEFAULT_POLICY_CONFIG,
  POLICY_INFO,
  type ActiveScheme,
  type PolicyConfig,
} from '../../src/economics/policies/registry';
import { comparePolicies, type PolicyOutcome } from '../../src/economics/simulation/comparisons';
import { compareFirm } from '../../src/economics/firm/firmModel';
import { ARCHETYPES, DEFAULT_FIRM_POLICY } from '../../src/economics/firm/archetypes';
import type { PaperParameters } from '../../src/economics/paper/types';

const { dataset } = loadCyprusDataset();
const rules = cyprusStatutoryRules(dataset);
const na = cyprusNationalAccounts2023(dataset);
const earn = cyprusMonthlyEarnings(dataset);
const FO_TO_GDP = (na.gdp - na.netTaxesOnProductionImports) / na.gdp; // factor output / GDP, 2023
const L: string[] = [];
const f = (x: number | null | undefined, d = 3) =>
  x === null || x === undefined || !Number.isFinite(x) ? '—' : x.toFixed(d);
const pc = (x: number | null | undefined, d = 2) =>
  x === null || x === undefined || !Number.isFinite(x) ? '—' : (x * 100).toFixed(d);

L.push(
  '# Policy comparison: Casas–Torres instruments vs exploratory policies E/F/G (Level 2 and Level 3)',
  '',
);
L.push(
  '*Generated by `tools/policies/policyReport.ts` (`npm run policies:report`). Do not edit by hand. Definitions and limitations: [POLICIES.md](POLICIES.md).*',
  '',
);
L.push('**These are long-run steady-state model comparisons, not forecasts.**');
L.push('- The adoption parameter is a CES weight, not an observed share of firms using AI.');
L.push('- E, F and G are new research hypotheses, not part of the paper.');
L.push(
  '- Company-level results (Level 3, final section) use invented archetypes and cannot be aggregated to national revenue.',
  '',
);

// --------------------------------------------------------------- historical financing (observed)
L.push(
  '## 1. Observed Social Insurance Fund financing (SIS final accounts; observed data, not simulated)',
  '',
);
const gdpByYear: Record<number, number> = { 2023: 33144.3, 2024: 36298.1, 2025: 38314.1, 2022: 29696.6 };
L.push(
  '| Year | Contributions excl. state, €m | State contribution, €m | Interest, €m | Expenditure, €m | Balance, €m | Contributions excl. state, % GDP | Status |',
);
L.push('|---|---:|---:|---:|---:|---:|---:|---|');
for (const y of fundSeries().filter((s) => s.year >= 2021)) {
  const g = gdpByYear[y.year];
  L.push(
    `| ${y.year} | ${contributionsExclState(y).toFixed(1)} | ${y.receipts.state.toFixed(1)} | ${y.receipts.interest.toFixed(1)} | ${y.expenditure.total.toFixed(1)} | ${y.balance.toFixed(1)} | ${g ? pc(contributionsExclState(y) / g) : '—'} | ${y.preliminary ? 'preliminary' : 'final'} |`,
  );
}
L.push('');
L.push(
  "The Level 2 policy target is the model's zero-adoption SS/Y. By the top-down calibration it equals 2023 contributions excluding the state share divided by factor-cost output (6.45%, about 5.62% of GDP).",
);
L.push(
  "The 5.2% state contribution, interest and the reserve are not part of the model's SS concept (MODEL_DEVIATIONS C3).",
  '',
);

// --------------------------------------------------------------- Level 2 comparisons
function table(rows: PolicyOutcome[]): void {
  L.push(
    '| Policy | Instrument | Status | Rate | SS/Y (% factor output) | ΔY % | ΔC % | ΔI % | ΔL % | Gross labour share | Net labour share | Employer burden (% Y) | CE welfare % | Welfare cost per € |',
  );
  L.push('|---|---|---|---:|---:|---:|---:|---:|---:|---:|---:|---:|---:|---:|');
  for (const r of rows) {
    const name = r.scheme === 'none' ? 'none (no new instrument)' : POLICY_INFO[r.scheme].label;
    const tag =
      r.scheme === 'none' ? '' : POLICY_INFO[r.scheme].origin === 'exploratory' ? ' (exploratory)' : '';
    L.push(
      `| ${r.code} | ${name}${tag} | ${r.status} | ${f(r.rate, 4)} | ${pc(r.ssToY)} | ${f(r.dY, 2)} | ${f(r.dC, 2)} | ${f(r.dI, 2)} | ${f(r.dL, 2)} | ${f(r.grossLabourShare)} | ${f(r.netLabourShare)} | ${pc(r.employerBurden)} | ${r.welfareCE === null ? '—' : pc(r.welfareCE)} | ${f(r.costPerRevenue, 3)} |`,
    );
  }
  L.push('');
}

const calibrations: [string, CalibrationResult][] = [];
for (const tech of ['B', 'A'] as const) {
  const a = cyprusAssumptions(dataset, tech);
  calibrations.push([
    `Technology ${tech}${tech === 'B' ? ' (default)' : ' (mandatory comparison)'}, β = 0.975 (primary)`,
    calibrateCyprus(na, rules, a, earn),
  ]);
  calibrations.push([
    `Technology ${tech}, β = 0.922 (K/Y-matching alternative)`,
    calibrateCyprus(na, rules, { ...a, betaMode: { kind: 'fromCapitalOutput' } }, earn),
  ]);
}

L.push('## 2. Level 2: required rates and economic effects (Cyprus calibration)', '');
L.push(
  'Each instrument is set to restore SS/Y to the target. Changes are relative to the economy without any new instrument at the same adoption level.',
);
L.push('Config:');
L.push(`- E coverage ${DEFAULT_POLICY_CONFIG.valueAddedCoverage};`);
L.push(
  `- F benchmark ${DEFAULT_POLICY_CONFIG.labourShareBenchmark} with coverage ${DEFAULT_POLICY_CONFIG.labourShareCoverage};`,
);
L.push('- G allowance 50% of the neutral return;');
L.push('- no payroll replacement;');
L.push(
  '- SI ceiling treated as indexed to wages (the fixed effective rate is exact under that assumption; the fixed-nominal sensitivity is in §3).',
  '',
);
const ranking: Record<string, number[]> = {};
for (const [title, cal] of calibrations) {
  const p = cal.params;
  const target = baselineSsTarget(p);
  const b = existenceBoundary(p);
  const star = b.kind === 'boundary' ? b.adoption : NaN;
  L.push(`### ${title}`, '');
  L.push(
    `Target SS/Y = ${pc(target)}% of factor output. Existence boundary of the untaxed economy: adoption ${f(star, 4)}.`,
    '',
  );
  const grid = [0.1, 0.2, 0.3, 0.4]
    .filter((x) => x < star - 0.005)
    .concat(star > 0.25 && star < 0.3 ? [0.25] : []);
  for (const a of [...new Set(grid)].sort()) {
    L.push(`**Adoption ${a}**`, '');
    const rows = comparePolicies(p, a, { target });
    table(rows);
    rows
      .filter((r) => r.status === 'solved' && r.costPerRevenue !== null)
      .sort((x, y) => (x.costPerRevenue ?? 0) - (y.costPerRevenue ?? 0))
      .forEach((r, i) => (ranking[r.code] ??= []).push(i + 1));
  }
}
L.push(
  '### Ranking by welfare cost per € raised (lower is better), across all calibrations and adoption levels above',
  '',
);
L.push('| Policy | Times ranked | Mean rank | Best | Worst |', '|---|---:|---:|---:|---:|');
for (const [code, ranks] of Object.entries(ranking).sort(
  (a, b) => a[1].reduce((s, x) => s + x, 0) / a[1].length - b[1].reduce((s, x) => s + x, 0) / b[1].length,
)) {
  L.push(
    `| ${code} | ${ranks.length} | ${f(ranks.reduce((s, x) => s + x, 0) / ranks.length, 2)} | ${Math.min(...ranks)} | ${Math.max(...ranks)} |`,
  );
}
L.push('', 'Policies not ranked in some cases were unattainable there (F, see §3).', '');

// --------------------------------------------------------------- sensitivities
L.push('## 3. Sensitivity analysis (Technology B, β = 0.975, adoption 0.3)', '');
const primary = calibrations[0]![1];
const p0: PaperParameters = primary.params;
const target0 = baselineSsTarget(p0);
const sens = (label: string, cfg: Partial<PolicyConfig>, schemes: readonly ActiveScheme[]) => {
  const rows = comparePolicies(p0, 0.3, {
    target: target0,
    config: { ...DEFAULT_POLICY_CONFIG, ...cfg },
    schemes,
  });
  L.push(`**${label}**`, '');
  table(rows);
};
sens('E with 50% payroll replacement (employer SS halved)', { payrollReplacement: 0.5 }, ['valueAdded']);
sens(
  'E with hospitality (NACE I) exempt: coverage = 1 − I/total GVA',
  { valueAddedCoverage: 1 - 2321.4 / (38314.1 - 4571.7) },
  ['valueAdded'],
);
for (const s of [0.4, 0.5, 0.6, 0.7])
  sens(`F with benchmark s̄ = ${s}`, { labourShareBenchmark: s }, ['labourShare']);
for (const fr of [0, 0.25, 0.75, 1])
  sens(`G with allowance = ${fr} × neutral return`, { excessProfitAllowance: { fractionOfNeutral: fr } }, [
    'excessProfit',
  ]);
{
  // SI ceiling fixed in nominal euros (wage-ceiling feedback)
  const W0 = primary.steadyState.ok ? primary.steadyState.levels.W : NaN;
  const ctx = {
    treatment: 'fixedNominal' as const,
    baselineWage: W0,
    bands: earn.bands,
    meanMonthly: earn.meanMonthly,
    monthlyCeiling: 5742,
  };
  const rows = comparePolicies(p0, 0.3, { target: target0, solver: (q, o) => solveWithCeiling(q, ctx, o) });
  const ref = solveWithCeiling({ ...p0, adoption: 0.3 }, ctx);
  L.push(
    `**SI ceiling fixed in nominal euros** (effective SI rate falls as wages rise; at adoption 0.3 without new instruments: wage scale ${f(ref.ceiling.wageScale, 3)}, effective rate ${f(ref.ceiling.effectiveRate, 4)} vs ${f(p0.taxes.employerSS, 4)} indexed)`,
    '',
  );
  table(rows);
}

// --------------------------------------------------------------- paper preset reference
L.push("## 4. Reference: the same comparison in the paper's own economy (Level 1 preset, adoption 0.3)", '');
L.push(
  'This shows how the exploratory policies rank in the Casas–Torres calibration itself, independent of Cyprus data.',
  '',
);
for (const tech of ['A', 'B'] as const) {
  L.push(`**Paper Technology ${tech}**`, '');
  table(comparePolicies(paperParameters(tech), 0.3));
}

// --------------------------------------------------------------- Level 3
L.push('## 5. Level 3: hypothetical company archetypes (statutory 2026 rules; NOT aggregable)', '');
L.push('Existing contributions use the exact payroll engine:');
L.push('- statutory 8.8% / 8.8% / 5.2%;');
L.push('- 13th salary attributed per Κ.Δ.Π. 289/2010 Reg. 8(3).');
L.push('');
L.push('Policy settings are illustrative assumptions:');
L.push('- E: 2% with an elasticity of 0.2;');
L.push('- F: 20% on the shortfall below a 50% benchmark, a 10% minimum margin and a 25% profit cap;');
L.push(
  '- G: 20% above a 6% normal return, with full AI-investment allowance, loss carryforward and profit shifting.',
  '',
);
L.push(
  '| Archetype (hypothetical) | GVA €k | Labour share | EBIT margin | Payroll above SI ceiling | Employer statutory €k | SIF receipts (all payers) €k | E €k (% GVA) | F €k (% GVA) | G €k (% GVA) |',
);
L.push('|---|---:|---:|---:|---:|---:|---:|---:|---:|---:|');
const k = (x: number) => (x / 1000).toFixed(0);
for (const firm of ARCHETYPES) {
  const c = compareFirm(firm, DEFAULT_FIRM_POLICY, rules);
  const a = c.accounts;
  const cell = (x: { liable: boolean; contribution: number; reason: string }) =>
    x.liable ? `${k(x.contribution)} (${pc(x.contribution / a.gva)}%)` : `0 (${x.reason})`;
  L.push(
    `| ${firm.name} | ${k(a.gva)} | ${f(a.labourShare)} | ${pc(a.operatingMargin, 1)}% | ${pc(a.shareAboveSiCeiling, 1)}% | ${k(a.employerStatutory)} | ${k(a.existingByRecipient.socialInsuranceFund)} | ${cell(c.valueAdded)} | ${cell(c.labourShare)} | ${cell(c.excessProfit)} |`,
  );
}
L.push('');
L.push('## 6. What these results can and cannot establish', '');
L.push(
  "- **Can:** compare instruments' steady-state distortions per unit of SS revenue within a transparent, tested model, and show the sensitivity to technology, β, coverage, benchmarks, allowances and the ceiling treatment.",
);
L.push('- **Cannot:**');
L.push('  - forecast Fund revenue;');
L.push('  - identify AI-generated profits;');
L.push('  - validate a labour-share or excess-profit contribution empirically;');
L.push('  - aggregate firm results to national revenue;');
L.push(
  '  - assess transition costs, tax competition beyond the stated profit-shifting assumption, or pension liabilities.',
);
L.push(`- Model SS/Y is per unit of factor-cost output; % of GDP ≈ × ${FO_TO_GDP.toFixed(3)} (2023 ratio).`);
mkdirSync('docs/policies', { recursive: true });
writeFileSync('docs/policies/POLICY_COMPARISON.md', L.join('\n') + '\n');
console.log('wrote docs/policies/POLICY_COMPARISON.md');
