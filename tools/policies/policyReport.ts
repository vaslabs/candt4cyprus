for (const a of ARCHETYPE_MODELS) {
  const generic = compareFirm(a.firm, DEFAULT_FIRM_POLICY, rules);
  const sector = compareFirm(
    a.firm,
    { ...DEFAULT_FIRM_POLICY, labourShare: { ...DEFAULT_FIRM_POLICY.labourShare, benchmarks: sectorB } },
    rules,
  );
  const acc = generic.accounts;
  L.push(`### ${a.firm.name}`, '');
  L.push('| Field | Value | Kind | Source |', '|---|---:|---|---|');
  for (const [k, v] of Object.entries(a.provenance)) {
    L.push(
      `| ${k} | ${Math.abs(v.value) >= 1000 ? Math.round(v.value).toLocaleString('en-GB') : f(v.value, 3)} | ${v.kind} | ${v.source}${v.note ? ` (${v.note})` : ''} |`,
    );
  }
  L.push(
    '',
    `GVA €${Math.round(acc.gva / 1000).toLocaleString('en-GB')}k; labour share ${f(acc.labourShare)}; EBIT margin ${pc(acc.operatingMargin, 1)}%; payroll above SI ceiling ${pc(acc.shareAboveSiCeiling, 1)}%.`,
  );
  const cell = (x: { liable: boolean; contribution: number; reason: string }) =>
    x.liable ? `€${Math.round(x.contribution / 1000)}k` : `€0k (${x.reason})`;
  L.push(
    `E: ${cell(generic.valueAdded)} · F (generic 50%): ${cell(generic.labourShare)} · F (sector benchmark ${f(sectorB[a.firm.sector] ?? 0.5)}): ${cell(sector.labourShare)} · G: ${cell(generic.excessProfit)}`,
    '',
  );
}

