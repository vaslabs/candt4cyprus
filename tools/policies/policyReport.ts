const { dataset } = loadCyprusDataset();
const rules = cyprusStatutoryRules(dataset);
const na = cyprusNationalAccounts2023(dataset);
const earn = cyprusMonthlyEarnings(dataset);
const FO_TO_GDP = (na.gdp - na.netTaxesOnProductionImports) / na.gdp;
const L: string[] = [];
const f = (x: number | null | undefined, d = 3) =>
  x === null || x === undefined || !Number.isFinite(x) ? '—' : x.toFixed(d);
const pc = (x: number | null | undefined, d = 2) =>
  x === null || x === undefined || !Number.isFinite(x) ? '—' : (x * 100).toFixed(d);
const nameOf = (r: PolicyOutcome) =>
  r.scheme === 'none'
    ? 'none (no new instrument)'
    : `${POLICY_INFO[r.scheme].label}${POLICY_INFO[r.scheme].origin === 'exploratory' ? ' [exploratory]' : ''}`;
const isG = (r: PolicyOutcome) => r.scheme === 'excessProfit' || r.scheme === 'capitalReturnLevy';

/** Results are reported in separate tables: revenue/status, real effects, distribution, efficiency. */
function tables(rows: PolicyOutcome[]): void {
  L.push('*Revenue and status*', '');
  L.push(
    '| Policy | Instrument | Status | Rate | SS/Y (% factor output) | Instrument revenue (% Y) | F regime | G on rents (% Y) | G on capital returns (% Y) |',
  );
  L.push('|---|---|---|---:|---:|---:|---|---:|---:|');
  for (const r of rows) {
    const flag =
      r.status === 'unattainable'
        ? '**unattainable**'
        : r.status === 'no-steady-state'
          ? '**no steady state**'
          : r.status;
    L.push(
      `| ${r.code} | ${nameOf(r)} | ${flag} | ${f(r.rate, 4)} | ${pc(r.ssToY)} | ${pc(r.instrumentRevenue)} | ${r.scheme === 'labourShare' ? (r.labourShareRegime ?? '—') : ''} | ${isG(r) ? pc(r.gOnRents, 3) : ''} | ${isG(r) ? pc(r.gOnCapitalReturns, 3) : ''} |`,
    );
  }
  L.push('', '*Real effects vs no new instrument (%)*', '');
  L.push(
    '| Policy | ΔGDP (Y) | ΔConsumption | ΔInvestment | ΔCapital K | ΔWorking time L |',
    '|---|---:|---:|---:|---:|---:|',
  );
  for (const r of rows)
    L.push(`| ${r.code} | ${f(r.dY, 2)} | ${f(r.dC, 2)} | ${f(r.dI, 2)} | ${f(r.dK, 2)} | ${f(r.dL, 2)} |`);
  L.push('', '*Distribution and burden*', '');
  L.push(
    '| Policy | Gross labour share | Net labour share | Gross capital share | Employer burden (% Y) |',
    '|---|---:|---:|---:|---:|',
  );
  for (const r of rows)
    L.push(
      `| ${r.code} | ${f(r.grossLabourShare)} | ${f(r.netLabourShare)} | ${f(r.grossCapitalShare)} | ${pc(r.employerBurden)} |`,
    );
  L.push(
    '',
    '*Efficiency (steady state; one indicator among several, not a measure of social desirability)*',
    '',
  );
  L.push('| Policy | CE welfare % | Welfare cost per € raised |', '|---|---:|---:|');
  for (const r of rows)
    L.push(`| ${r.code} | ${r.welfareCE === null ? '—' : pc(r.welfareCE)} | ${f(r.costPerRevenue, 3)} |`);
  L.push('');
}

L.push('# Policy comparison: Casas–Torres instruments vs exploratory policies E/F/G/G′', '');
L.push(
  '*Generated by `tools/policies/policyReport.ts` (`npm run policies:report`). Do not edit by hand. Definitions and limitations: [POLICIES.md](POLICIES.md).*',
  '',
);
L.push(
  '> **Read first.** Every result here is a long-run steady-state model result, conditional on the model and the stated assumptions. None is a forecast or a general policy ranking for Cyprus.',
);
L.push('> - The adoption parameter is a CES weight, not a share of firms using AI.');
L.push('> - E, F, G and G′ are new research hypotheses.');
L.push(
  '> - Company-level and SBS-cell results are scenario calculations and are not aggregated to national revenue.',
  '',
);

// ------------------------------------------------------------- 1. Observed
L.push('## 1. Observed Social Insurance Fund financing (SIS final accounts; observed, not simulated)', '');
const gdpByYear: Record<number, number> = { 2022: 29696.6, 2023: 33144.3, 2024: 36298.1, 2025: 38314.1 };
L.push(
  '| Year | Contributions excl. state, €m | State contribution, €m | Interest, €m | Expenditure, €m | Balance, €m | Contributions excl. state, % GDP | Status |',
  '|---|---:|---:|---:|---:|---:|---:|---|',
);
for (const y of fundSeries().filter((s) => s.year >= 2021)) {
  const g = gdpByYear[y.year];
  L.push(
    `| ${y.year} | ${contributionsExclState(y).toFixed(1)} | ${y.receipts.state.toFixed(1)} | ${y.receipts.interest.toFixed(1)} | ${y.expenditure.total.toFixed(1)} | ${y.balance.toFixed(1)} | ${g ? pc(contributionsExclState(y) / g) : '—'} | ${y.preliminary ? 'preliminary' : 'final'} |`,
  );
}
L.push(
  '',
  "Level 2 target = the model's zero-adoption SS/Y. This equals 2023 contributions excluding the state share divided by factor-cost output (6.45%, about 5.62% of GDP).",
  '',
);

// ------------------------------------------------------------- 2. Headline Level 2
const cals: [string, CalibrationResult][] = [];
for (const tech of ['B', 'A'] as const) {
  const a = cyprusAssumptions(dataset, tech);
  cals.push([
    `Technology ${tech}${tech === 'B' ? ' (default)' : ' (mandatory comparison)'}, β = 0.975 (primary)`,
    calibrateCyprus(na, rules, a, earn),
  ]);
  cals.push([
    `Technology ${tech}, β = 0.922 (K/Y-matching alternative)`,
    calibrateCyprus(na, rules, { ...a, betaMode: { kind: 'fromCapitalOutput' } }, earn),
  ]);
}
L.push(
  '## 2. Level 2: required rates and effects (Cyprus calibration, objective: restore the Fund financing target)',
  '',
);
L.push('Defaults:');
L.push("- G uses **neutral allowances**: each capital's own required return.");
L.push(
  `- G′ is the reduced-allowance capital-return levy, with allowance = ${DEFAULT_POLICY_CONFIG.capitalReturnLevyFraction} × neutral.`,
);
L.push('- F uses the generic 50% benchmark.');
L.push('- E has full coverage.');
L.push('- The SI ceiling is indexed to wages.', '');
const ranking: Record<string, number[]> = {};
for (const [title, cal] of cals) {
  const p = cal.params;
  const target = baselineSsTarget(p);
  const b = existenceBoundary(p);
  const star = b.kind === 'boundary' ? b.adoption : NaN;
  L.push(
    `### ${title}`,
    '',
    `Target SS/Y = ${pc(target)}% of factor output; untaxed existence boundary: adoption ${f(star, 4)}.`,
    '',
  );
  for (const a of [0.1, 0.2, 0.3, 0.4].filter((x) => x < star - 0.005)) {
    L.push(`**Adoption ${a}**`, '');
    const rows = comparePolicies(p, a, { target });
    tables(rows);
    rows
      .filter((r) => r.status === 'solved' && r.costPerRevenue !== null)
      .sort((x, y) => (x.costPerRevenue ?? 0) - (y.costPerRevenue ?? 0))
      .forEach((r, i) => (ranking[r.code] ??= []).push(i + 1));
  }
}
L.push('### Ranking by welfare cost per € raised across §2 (a conditional model result)', '');
L.push('| Policy | Times ranked | Mean rank | Best | Worst |', '|---|---:|---:|---:|---:|');
const mean = (xs: number[]) => xs.reduce((s, x) => s + x, 0) / xs.length;
for (const [code, ranks] of Object.entries(ranking).sort((a, b) => mean(a[1]) - mean(b[1]))) {
  L.push(
    `| ${code} | ${ranks.length} | ${f(mean(ranks), 2)} | ${Math.min(...ranks)} | ${Math.max(...ranks)} |`,
  );
}
L.push('');
L.push('- **E ranks first in every long-run configuration above.**');
L.push(
  '- That holds only within a representative-firm, long-run model with perfectly elastic capital supply, uniform coverage and no avoidance costs. §3 shows where it changes.',
);
L.push(
  '- G (neutral) is never ranked, because it is unattainable: it raises nothing in a competitive economy without rents.',
  '',
);

// ------------------------------------------------------------- 3. E sensitivity
const primary = cals[0]![1];
const p0: PaperParameters = primary.params;
const t0 = baselineSsTarget(p0);
L.push(
  '## 3. Policy E: model dependence and sensitivity (Technology B, β = 0.975, adoption 0.3 unless stated)',
  '',
);
L.push('**Omitted heterogeneity.** The Level 2 model has one representative firm. It cannot represent:');
L.push('- differences in firm size, sector, margin or loss position;');
L.push('- avoidance through reclassification or relocation;');
L.push('- international profit shifting.');
L.push('Those mechanisms are covered below by separate, labelled scenario calculations.', '');
L.push('### 3.1 Coverage (long run): coverage alone is not a behavioural model', '');
L.push('| Coverage | Statutory rate | Welfare cost per € |', '|---:|---:|---:|');
for (const r of valueAddedCoverageSweep(p0, 0.3, t0, [0.24, 0.49, 0.76, 1]))
  L.push(`| ${r.coverage} | ${f(r.rate, 4)} | ${f(r.costPerRevenue, 4)} |`);
L.push(
  '',
  'Because (τ, c) ≡ (τc, 1) for a representative firm, coverage only rescales the statutory rate; the welfare cost per € is unchanged.',
  '',
);
L.push("### 3.2 Structural parameters (long run): where could E's rank change?", '');
const sw = structuralSweep(p0, {
  elasticityKL: [0.5, 0.7, 0.9, 1.1],
  elasticityAuto: [1.5, 2, 3],
  adoption: [0.1, 0.3],
});
const notFirst = sw.filter((r) => r.eRank !== null && r.eRank !== 1);
L.push(
  `${sw.length} points (ε_KL ∈ {0.5,0.7,0.9,1.1} × σ_auto ∈ {1.5,2,3} × adoption ∈ {0.1,0.3}; each point measured against its own zero-adoption SS/Y; other calibrated parameters held fixed).`,
);
L.push(
  `E ranked first in ${sw.filter((r) => r.eRank === 1).length}; not first in ${notFirst.length}; no instrument solvable in ${sw.filter((r) => r.eRank === null).length}.`,
  '',
);
for (const r of notFirst)
  L.push(`- ${r.label}: best ${r.bestScheme}, E cost ${f(r.eCost)}, D cost ${f(r.dCost)}`);
L.push('### 3.3 Capital mobility: capital fixed at its pre-reform level (short-run scenario)', '');
L.push(
  'With an immobile capital stock, taxes on capital income or robot use fall on a fixed factor and leave the allocation unchanged. E still distorts labour supply.',
  '',
);
const sr = shortRunComparison(p0, 0.3, t0);
tables(sr);
L.push(
  `**Region where E's relative performance changes:** with capital fixed, E ranks ${rankPoint('sr', sr).eRank ?? '—'} of ${sr.filter((r) => r.status === 'solved').length} solved instruments. The long-run ranking therefore depends on capital being supplied elastically, and should not be read as a short- or medium-run result.`,
  '',
);
L.push('### 3.4 Objective: revenue-neutral swap (replace 50% of employer SS; no additional revenue)', '');
tables(comparePolicies(p0, 0.3, { objective: { kind: 'revenueNeutralSwap', replacement: 0.5 } }));
L.push(
  '### 3.5 Sector exemptions, SMEs vs large enterprises, low-margin sectors (SBS 2024, business economy only)',
  '',
);
L.push('| SME threshold (exempt below) | Liable share of SBS value added |', '|---|---:|');
const thresholdLabel: Record<string, string> = {
  '0-9': 'none',
  '10-19': '10 employees',
  '20-49': '20 employees',
  '50-249': '50 employees',
  GE250: '250 employees',
};
for (const s of ['0-9', '10-19', '20-49', '50-249', 'GE250'] as const)
  L.push(`| ${thresholdLabel[s]} | ${pc(smeExemptionCoverage(s).coverage, 1)}% |`);
L.push(
  '',
  '| NACE | Labour share | GOS / VA | E at 2.5% as % of operating surplus | VA share in firms ≥ 10 employees | F at 50% benchmark | Note |',
  '|---|---:|---:|---:|---:|---|---|',
);
for (const r of sbsSectorScenario(0.025, '10-19')) {
  L.push(
    `| ${r.nace} | ${f(r.labourShare)} | ${f(r.gosShare)} | ${pc(r.eShareOfGos, 1)}% | ${pc(r.vaShareAboveThreshold, 1)}% | ${r.fGeneric} | ${r.note} |`,
  );
}
L.push('');
L.push(
  '- E taxes value added regardless of profitability. Its burden relative to operating surplus is highest in labour-intensive, low-margin sectors (M, N, H).',
);
L.push(
  '- Exempting SMEs concentrates the base on larger firms. In the macro model that only rescales the rate (§3.1), but in reality it creates threshold effects that are not modelled.',
  '',
);
L.push('### 3.6 Behavioural elasticities and margins (Level 3, constructed software archetype)', '');
const soft = ARCHETYPE_MODELS[2]!.firm;
L.push(
  '| Base elasticity (E, F); G shifting semi-elasticity = 2× | E €k | F €k | G €k |',
  '|---:|---:|---:|---:|',
);
for (const r of firmElasticitySweep(soft, DEFAULT_FIRM_POLICY, rules, [0, 0.25, 0.5, 1, 2])) {
  L.push(
    `| ${r.elasticity} | ${(r.valueAdded / 1000).toFixed(0)} | ${(r.labourShare / 1000).toFixed(0)} | ${(r.excessProfit / 1000).toFixed(0)} |`,
  );
}
L.push('', '| EBIT margin | E €k | F €k | G €k |', '|---:|---:|---:|---:|');
for (const m of [0.4, 0.1, 0.03, -0.1]) {
  const c = compareFirm(withOperatingMargin(soft, rules, m), DEFAULT_FIRM_POLICY, rules);
  L.push(
    `| ${pc(m, 0)}% | ${(c.valueAdded.contribution / 1000).toFixed(0)} | ${(c.labourShare.contribution / 1000).toFixed(0)}${c.labourShare.liable ? '' : ' (' + c.labourShare.reason + ')'} | ${(c.excessProfit.contribution / 1000).toFixed(0)} |`,
  );
}
L.push(
  '',
  'E remains payable by low-margin and loss-making firms. F (with its profitability condition) and G do not.',
  '',
);

// ------------------------------------------------------------- 4. G
L.push('## 4. Policy G: genuine rents vs ordinary capital returns', '');
L.push(
  '**Competitive model (no rents):** with neutral per-capital allowances, G raises nothing and cannot finance the target. G′ is shown for comparison and taxes ordinary returns.',
  '',
);
tables(comparePolicies(p0, 0.3, { target: t0, schemes: ['excessProfit', 'capitalReturnLevy'] }));
L.push(
  '**Exploratory rents extension (markup 10% over marginal cost; not in the paper):** pure profits exist. Neutral G taxes them without changing the allocation.',
  '',
);
