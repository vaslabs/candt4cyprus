#!/usr/bin/env bash
# Records the policy-maker walkthrough (1920×1080, English captions) and encodes it for the web.
# Requires ffmpeg.
#
# The video is NOT committed. public/media/policy-walkthrough.{mp4,jpg} is the frozen first
# recording, kept only as a fallback. New recordings are published as GitHub release assets;
# the deploy workflow downloads them into the built site (tools/demo/fetchWalkthrough.sh).
#
#   RELEASE=walkthrough-v2 npm run demo:walkthrough            # record; writes the transcript
#   RELEASE=walkthrough-v2 UPLOAD=1 SKIP_RECORD=1 npm run demo:walkthrough   # publish (gh)
#
# Outputs: tools/demo/out/walkthrough/policy-walkthrough.{mp4,jpg} (ignored) and
# src/content/policyWalkthrough.json (committed: release tag, duration and timed transcript).
set -euo pipefail
cd "$(dirname "$0")/../.."
OUT=tools/demo/out/walkthrough
RELEASE=${RELEASE:-$(node -p "require('./src/content/policyWalkthrough.json').release")}
MP4="$OUT/policy-walkthrough.mp4"
JPG="$OUT/policy-walkthrough.jpg"

if [ "${SKIP_RECORD:-0}" != 1 ]; then
  npx playwright test -c tools/demo/playwright.walkthrough.config.ts "$@"
  # Variable-rate screencast frames -> constant 30 fps. Screen content compresses well at CRF 30.
  ffmpeg -loglevel error -y -f concat -safe 0 -i "$OUT/frames.txt" \
    -vf "scale=1920:1080:flags=lanczos,fps=30,format=yuv420p" \
    -c:v libx264 -profile:v high -preset slow -crf 30 -tune stillimage -an \
    -movflags +faststart "$MP4"
  # Poster: the opening question card.
  ffmpeg -loglevel error -y -ss 3 -i "$MP4" -frames:v 1 -vf "scale=1280:-2" -q:v 4 "$JPG"
  DURATION=$(ffprobe -v error -show_entries format=duration -of csv=p=0 "$MP4")
  RELEASE="$RELEASE" DURATION="$DURATION" node -e '
    const fs = require("node:fs");
    const entries = JSON.parse(fs.readFileSync(process.argv[1], "utf8"));
    const doc = { release: process.env.RELEASE, duration: Math.round(Number(process.env.DURATION) * 10) / 10, entries };
    fs.writeFileSync("src/content/policyWalkthrough.json", JSON.stringify(doc, null, 2) + "\n");
  ' "$OUT/transcript.json"
  npx prettier --write src/content/policyWalkthrough.json >/dev/null
  ffprobe -v error -show_entries format=duration,size -show_entries stream=width,height,codec_name \
    -of compact "$MP4"
  echo "Transcript written for release $RELEASE. Publish with UPLOAD=1 before deploying."
fi

if [ "${UPLOAD:-0}" = 1 ]; then
  # Releases are immutable by convention: create a new tag for every recording.
  gh release create "$RELEASE" "$MP4" "$JPG" \
    --title "Policy-maker walkthrough ($RELEASE)" \
    --notes "Captioned walkthrough video served by the app (see src/content/policyWalkthrough.json). Generated by npm run demo:walkthrough." \
    --latest=false
fi
