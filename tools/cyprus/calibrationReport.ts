/**
 * Generates docs/cyprus/CALIBRATION_REPORT.md (deterministic). Run: npm run cyprus:report
 */
import { writeFileSync } from 'node:fs';
import {
  calibrateCyprus,
  CYPRUS_PRESET_ID,
  type CalibrationResult,
} from '../../src/economics/cyprus/calibration';
import { calibrationCrossChecks } from '../../src/economics/cyprus/crossChecks';
import {
  cyprusAssumptions,
  cyprusCrossCheckInputs,
  cyprusMonthlyEarnings,
  cyprusNationalAccounts2023,
  cyprusStatutoryRules,
  loadCyprusDataset,
} from '../../src/economics/cyprus/defaults';
import { employeeResult, salarySchedule } from '../../src/economics/cyprus/employerCosts';
import { total } from '../../src/economics/cyprus/contributionRules';

const { dataset, sources } = loadCyprusDataset();
const rules = cyprusStatutoryRules(dataset);
const na = cyprusNationalAccounts2023(dataset);
const base = cyprusAssumptions(dataset, 'B');
const earn = cyprusMonthlyEarnings(dataset);
const runs: [string, CalibrationResult][] = [
  ['A. Primary: β = 0.975 (structural assumption; K/Y NOT targeted)', calibrateCyprus(na, rules, base, earn)],
  [
    'B. Alternative: β from the 2023 capital/output ratio (K/Y targeted)',
    calibrateCyprus(na, rules, { ...base, betaMode: { kind: 'fromCapitalOutput' } }, earn),
  ],
  [
    'C. As A, but statutory bottom-up SI rate (Fund contributions untargeted)',
    calibrateCyprus(na, rules, { ...base, ssRateMode: 'statutoryBottomUp' }, earn),
  ],
  [
    'D. Technology A comparison (otherwise as A)',
    calibrateCyprus(na, rules, { ...base, technology: 'A' }, earn),
  ],
];
const f = (x: number, d = 4) => (Number.isFinite(x) ? x.toFixed(d) : 'n/a (data gap)');
const eur = (x: number) => `€${Math.round(x).toLocaleString('en-GB')}`;
const L: string[] = [];
L.push('# Cyprus 2026 calibration report (Level 2)', '');
L.push(
  `*Generated by \`tools/cyprus/calibrationReport.ts\` (\`npm run cyprus:report\`). Preset \`${CYPRUS_PRESET_ID}\`. Do not edit by hand.*`,
  '',
);
L.push(
  `Dataset: ${dataset.parameters.length} parameters; source register: ${sources.length} sources (all accessed 2026-11-19).`,
);
const byCat = dataset.parameters.reduce<Record<string, number>>(
  (m, p) => ((m[p.category] = (m[p.category] ?? 0) + 1), m),
  {},
);
const byVer = dataset.parameters.reduce<Record<string, number>>(
  (m, p) => ((m[p.verification] = (m[p.verification] ?? 0) + 1), m),
  {},
);
L.push(
  `By category: ${Object.entries(byCat)
    .map(([k, v]) => `${k} ${v}`)
    .join(', ')}. By verification: ${Object.entries(byVer)
    .map(([k, v]) => `${k} ${v}`)
    .join(', ')}.`,
  '',
);
L.push(
  'This is **not** a forecast. The model is a long-run steady state of a closed, representative-agent economy with no growth, and no Cyprus automation estimate exists.',
  '',
);

for (const [title, r] of runs) {
  L.push(`## Calibration ${title}`, '');
  L.push('| Parameter | Value | How obtained |', '|---|---:|---|');
  const p = r.params;
  L.push(
    `| β | ${f(p.beta)} | ${title.startsWith('B') ? 'Euler (25) with R_k = s_K/(K/Y)' : 'structural assumption (paper value)'} |`,
  );
  L.push(`| γ | ${f(p.gamma)} | labour supply (24) matched to hours share ${f(r.derived.hoursShare, 3)} |`);
  L.push(
    `| capital weight w_K | ${f(p.capitalShareParam)} | unit-cost identity with s_K = ${f(1 - r.derived.labourCostShare)} |`,
  );
  L.push(`| δ_k | ${f(p.deltaK)} | CFC / net capital stock (2023) |`);
  L.push(`| R_k | ${f(r.derived.Rk)} | ${title.startsWith('B') ? 's_K/(K/Y)' : 'Euler (25) given β'} |`);
  L.push(`| τ^c | ${f(p.taxes.consumption)} | D21 / (C + G − D21) |`);
  L.push(`| τ^l | ${f(p.taxes.labour)} | D51A / (D11 + B3G) |`);
  L.push(`| τ^k | ${f(p.taxes.capital)} | D51B / net capital income |`);
  L.push(
    r.derived.ssRateMode === 'fundAccounts'
      ? `| τ^sse = τ^ssw | ${f(p.taxes.employerSS)} | top-down: model SS/Y matches Fund contributions (excl. state) / factor output = ${f(r.derived.fundSsRatio)} (SIS accounts ${na.year}). Statutory bottom-up would give ${f(r.derived.statutoryBottomUpRate)}. |`
      : `| τ^sse = τ^ssw | ${f(p.taxes.employerSS)} | bottom-up: 8.8% × insurable share ${f(r.derived.siInsurableShare)} (${r.derived.insurableShareMethod}, CYSTAT ${r.derived.earningsYear} monthly earnings) |`,
  );
  L.push(
    `| ρ, υ/σ, δ_d | ${p.elasticityKL}, ${p.elasticityAuto}, ${p.deltaD} | assumptions (paper values) with ranges |`,
  );
  L.push('', '| Check | Result | Detail |', '|---|:---:|---|');
  for (const c of r.checks) L.push(`| ${c.name} | ${c.pass ? 'PASS' : '**FAIL**'} | ${c.detail} |`);
  L.push('', '| Moment | Data | Model | Targeted | Note |', '|---|---:|---:|:---:|---|');
  for (const m of r.moments)
    L.push(`| ${m.name} | ${f(m.data)} | ${f(m.model)} | ${m.targeted ? 'yes' : 'no'} | ${m.note} |`);
  L.push('');
}

L.push('## External cross-checks (calibration A)', '');
const r0 = runs[0]![1];
const gdp25 = 38314.1;
const fo25 = gdp25 - 4571.7;
L.push('| Check | Model | Reference | Units | Caveat |', '|---|---:|---:|---|---|');
for (const c of calibrationCrossChecks(r0, cyprusCrossCheckInputs(dataset), gdp25, fo25)) {
  L.push(`| ${c.name} | ${f(c.model)} | ${f(c.reference)} | ${c.units} | ${c.caveat} |`);
}
L.push('');

L.push('## Statutory examples (2026 rules), showing the €5,742/month ceiling', '');
L.push(
  '| Gross salary (12 payments) | SI insurable | Employee SI | Employer SI | State SI (not employer cost) | Employee GHS | Employer funds (GHS+SCF+Red.+HRD) | Income tax | Employer labour cost | Net pay |',
);
L.push('|---:|---:|---:|---:|---:|---:|---:|---:|---:|---:|');
for (const s of [15000, 30000, 50000, 68904, 100000, 250000]) {
  const e = employeeResult(salarySchedule(s), rules);
  const c = e.contributions.lines;
  L.push(
    `| ${eur(s)} | ${eur(e.contributions.siInsurableAnnual)} | ${eur(total(c, { item: 'si', payer: 'employee' }))} | ${eur(total(c, { item: 'si', payer: 'employer' }))} | ${eur(total(c, { item: 'si', payer: 'state' }))} | ${eur(e.employeeGHS)} | ${eur(e.employerStatutory - total(c, { item: 'si', payer: 'employer' }))} | ${eur(e.incomeTax.tax)} | ${eur(e.employerLabourCost)} | ${eur(e.netPay)} |`,
  );
}
L.push(
  '',
  'Income tax applies the 1/5 cap on deductible SI and GHS contributions. Personal deductions (children, housing) are not applied unless supplied.',
  '',
);

L.push("## Do the paper's propositions carry over? (MODEL_DEVIATIONS C10)", '');
L.push(
  '- **Proposition 1 (ratio invariance)** holds inside this model only while τ^sse and τ^ssw are held fixed (condition C4).',
);
L.push(
  '  With a per-person ceiling fixed in euros, the insurable share falls as wages rise. Example: a 20% rise in mean wages with the ceiling unchanged lowers the insurable share',
);
const { insurableShare } = await import('../../src/economics/cyprus/earningsDistribution');
const m = earn.meanMonthly;
const sh0 = insurableShare({ mean: m, logSd: base.earningsLogSd }, 5742);
const sh1 = insurableShare({ mean: 1.2 * m, logSd: base.earningsLogSd }, 5742);
L.push(
  `  from ${f(sh0)} to ${f(sh1)} (lognormal), so the effective SI rate falls from ${f(0.088 * sh0)} to ${f(0.088 * sh1)}. Results that depend on wage levels are therefore not invariant.`,
);
L.push(
  '- **Proposition 3 (closed-form Tech A rates)** inherits the same condition, and it applies only to Technology A. The default Cyprus technology is B (assumption).',
);
L.push(
  '- In practice the Cyprus ceiling is adjusted every year. Indexing the ceiling to wages keeps the insurable share constant (tested). Whether to index is a scenario choice.',
  '',
);
writeFileSync('docs/cyprus/CALIBRATION_REPORT.md', L.join('\n') + '\n');
console.log('wrote docs/cyprus/CALIBRATION_REPORT.md');
